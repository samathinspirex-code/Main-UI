/** Point a /programs/<old-slug> path at the current slug; any other path passes through. */
export function currentProgramPath(path: string): string {
  const match = path.match(/^\/programs\/([^/?#]+)(.*)$/);
  const next = match ? LEGACY_PROGRAM_SLUGS[match[1]] : undefined;
  return match && next ? `/programs/${next}${match[2]}` : path;
}
